#!/usr/bin/env python3
"""
Regenerates demo/compose.faultlens.yaml and demo/faultlens/locustfile.py from the
upstream OpenTelemetry Demo files, so upstream stays untouched.

    cd demo && python3 faultlens/build_compose.py      (needs: pip install pyyaml)
"""
import os
import yaml

os.chdir(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))

KEEP = ["frontend-proxy", "frontend", "load-generator", "cart", "valkey-cart",
        "checkout", "payment", "product-catalog", "astronomy-db", "currency",
        "shipping", "quote", "email", "image-provider",
        "flagd", "otel-collector"]

# ---- 1. locustfile: HTTP-only, no ads, no AI agent ----
src = open("src/load-generator/locustfile.py").read()
for name in ("get_ads", "ask_agent", "get_recommendations"):
    pat = f"    @task(3)\n    def {name}("
    assert pat in src, f"upstream locustfile changed: {name}"
    src = src.replace(pat, f"    # [FaultLens] disabled: service not running in trimmed shop\n    def {name}(")
header = ("# [FaultLens] Generated from src/load-generator/locustfile.py.\n"
          "# Changes: get_ads, get_recommendations, ask_agent disabled (those services are not\n"
          "# part of the trimmed shop). Regenerate with demo/faultlens/build_compose.py.\n")
open("faultlens/locustfile.py", "w").write(header + src)

# ---- 2. compose ----
c = yaml.safe_load(open("compose.yaml"))
DROPPED = set(c["services"]) - set(KEEP)
svcs = {}
for name in KEEP:
    s = c["services"][name]
    s.pop("build", None)  # never build locally — pull prebuilt images only
    s["logging"] = {"driver": "json-file", "options": {"max-size": "2m", "max-file": "1"}}
    if isinstance(s.get("depends_on"), dict):
        for d in list(s["depends_on"]):
            if d in DROPPED:
                del s["depends_on"][d]
    svcs[name] = s


def set_env(s, key, val):
    env = s["environment"]
    env[:] = [e for e in env if e.split("=")[0] != key] + [f"{key}={val}"]


def set_mem(s, m):
    s["deploy"]["resources"]["limits"]["memory"] = m


lg = svcs["load-generator"]
set_env(lg, "LOCUST_BROWSER_TRAFFIC_ENABLED", "false")
set_env(lg, "LOCUST_USERS", "${FAULTLENS_LOCUST_USERS:-3}")
set_env(lg, "LOCUST_SPAWN_RATE", "1")
set_mem(lg, "250M")

# astronomy-db: upstream healthcheck runs `pg_isready` as root → Postgres logs
# 'FATAL: role "root" does not exist' every 5 s. Harmless, but noisy in demo logs.
svcs["astronomy-db"]["healthcheck"]["test"] = ["CMD-SHELL", "pg_isready -U postgres"]
lg["volumes"] = ["./faultlens/locustfile.py:/usr/src/app/locustfile.py:ro"]

oc = svcs["otel-collector"]
oc["command"] = ["--config=/etc/otelcol-config.yml"]
oc["volumes"] = ["${DOCKER_SOCK}:/var/run/docker.sock:ro",
                 "./faultlens/otelcol-faultlens.yml:/etc/otelcol-config.yml:ro"]
oc["extra_hosts"] = ["host.docker.internal:host-gateway"]
set_mem(oc, "250M")
set_env(oc, "GOMEMLIMIT", "200MiB")

out = {"name": "faultlens-shop", "networks": c["networks"], "services": svcs}
head = f"""# ─────────────────────────────────────────────────────────────────────────────
# FaultLens — trimmed Astronomy Shop (GENERATED by faultlens/build_compose.py — edit that)
#
# {len(KEEP)} containers. Dropped from upstream core: {", ".join(sorted(DROPPED))}
# All images are pulled pre-built (no local builds). Collector exports ONLY to
# FaultLens (host:8000) with batching — see faultlens/otelcol-faultlens.yml.
#
#   docker compose -f compose.faultlens.yaml up -d
#   docker compose -f compose.faultlens.yaml down
# Shop UI: http://localhost:8080      Load generator UI: http://localhost:8080/loadgen/
# ─────────────────────────────────────────────────────────────────────────────
"""
open("compose.faultlens.yaml", "w").write(head + yaml.safe_dump(out, sort_keys=False, width=200))
print(f"wrote compose.faultlens.yaml ({len(KEEP)} services); dropped: {sorted(DROPPED)}")
